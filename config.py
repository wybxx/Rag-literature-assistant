"""
config.py —— 全局配置

所有可以调的参数都放这里。像"chunk 大小怎么定的"这类问题，
答案就来自这里：改成不同值，观察检索效果的变化。
"""
import os

from dotenv import load_dotenv

load_dotenv()  # 读取 .env 文件里的环境变量（API key 别硬编码进代码！）

# ============ LLM 配置（对话模型：DeepSeek） ============
# 注意：DeepSeek 只有对话接口，没有 Embedding 接口（官方至今不提供），
# 所以向量化单独走硅基流动（SiliconFlow），接口同为 OpenAI 兼容格式。
API_KEY = os.getenv("LLM_API_KEY", "")
BASE_URL = os.getenv("LLM_BASE_URL", "https://api.deepseek.com")
CHAT_MODEL = os.getenv("LLM_CHAT_MODEL", "deepseek-chat")

# ============ Embedding 配置（向量化模型：硅基流动） ============
# https://cloud.siliconflow.cn 注册 → API 密钥 → 填到 .env 的 EMBEDDING_API_KEY
# BAAI/bge-m3 是开源中文向量模型的标杆，免费额度对这个项目绰绰有余
EMBEDDING_API_KEY = os.getenv("EMBEDDING_API_KEY", "")
EMBEDDING_BASE_URL = os.getenv("EMBEDDING_BASE_URL", "https://api.siliconflow.cn/v1")
EMBEDDING_MODEL = os.getenv("EMBEDDING_MODEL", "BAAI/bge-m3")

# ============ 分块（Chunking）配置 ============
CHUNK_SIZE = 500      # 每块最大字符数。太小→语义被切断；太大→检索不精准、上下文浪费
CHUNK_OVERLAP = 50    # 相邻块的重叠字符数，防止关键句刚好被切断

# ============ 检索（Retrieval）配置 ============
TOP_K = 4             # 最终送进 LLM 的文本块数量
RECALL_K = 12         # 第一阶段向量召回的候选数（要大于 TOP_K，给 Rerank 留挑选余地）

# ============ Rerank 配置（重排序：两阶段检索的第二阶段） ============
# 向量检索是"双塔"：问题和文档各自编码再比距离，快但糙，只能"大概像不像"。
# Rerank 是"交叉编码器"：把【问题+文档】拼一起读，逐词交叉比对，精但慢。
# 所以标准架构：向量先从全库捞出 RECALL_K 个候选 → Rerank 精选 TOP_K 个。
# 硅基流动提供 BAAI/bge-reranker-v2-m3，和 EMBEDDING_API_KEY 用同一把钥匙。
RERANK_ENABLED = True
RERANK_MODEL = os.getenv("RERANK_MODEL", "BAAI/bge-reranker-v2-m3")
# 相关性分数阈值：Rerank 打分低于它的候选块直接丢弃，不送进 LLM。
# 作用：宁可少给几个块，也不让无关内容污染上下文（避免模型被带偏）。
#
# 【标定实验】阈值不是拍脑袋定的——用已知相关/无关的"问题-文档对"实测：
#   0.894  相关｜中文问题 vs 中文定义（同语言）
#   0.221~0.381  相关｜中文问题 vs 英文论文正文/图注（跨语言分数天然偏低）
#   0.0006 无关｜中文问题 vs 无关英文块
# 相关与无关之间隔着约三个数量级的鸿沟，取 0.05 即可干净分开；
# 若取 0.3 会把所有跨语言命中（中文提问查英文文献）全部误杀。
RERANK_THRESHOLD = 0.05

# ============ 混合检索（Hybrid Search）配置 ============
# 为什么需要"向量 + 关键词"双通道？
#   向量检索擅长"语义相近"，但对【专有名词/型号/代码符号】不敏感——
#   问"bge-reranker 是什么"，它可能给你返回"embedding 模型介绍"。
#   关键词检索（BM25）恰好相反：字面命中能力强，但不懂同义词。
#   所以工业界标准做法是两条通道各召回一批，再用 RRF 算法融合排名。
HYBRID_ENABLED = True
RRF_K = 60                 # RRF 公式中的平滑常数，原论文推荐值 60，一般不用改
HYBRID_WEIGHT_VECTOR = 1.0  # 向量通道在融合中的权重（可调，观察效果变化）
HYBRID_WEIGHT_BM25 = 1.0    # BM25 通道在融合中的权重

# ============ 类型保底配额 ============
# 表格/插图块容易被正文块和摘要块挤出候选池（真实案例：问"实验结果数据"，
# 结果表在向量通道排 36 名，进不了 RECALL_K=12 的候选池，Rerank 没机会看到）。
# 这里给它们留保底名额，让 Rerank 阶段做最终裁决——分数不行照样被阈值过滤掉。
RECALL_DEEP_K = 48          # 各通道"宽捞"深度：先多召回再由 RRF 精简 + Rerank 裁决
RECALL_QUOTA_TABLE = 2      # 候选池中表格块至少几个（不足则从融合排名补入）
RECALL_QUOTA_IMAGE = 1      # 候选池中插图块至少几个

# ============ 多轮对话配置 ============
# 用户说"它有什么缺点？"时，检索器看不到"它"指什么，必然召回失败。
# 解决办法：先用 LLM 把追问改写成独立可检索的问题，再走检索。
QUERY_REWRITE_ENABLED = True
MAX_HISTORY_TURNS = 3       # 送给改写模型的历史轮数（太多浪费 token）

# ============ 跨语言查询扩展（Multi-Query Retrieval） ============
# 研究生的典型场景：用中文提问，文献却是英文。向量模型跨语言能力有限，
# BM25 更是几乎失效（中文词根本匹配不到英文文本，实测分数为 0）。
# 解法：先用 LLM 把中文问题翻译出一个英文变体，两路查询同时检索再融合——
# 这也是工业界多语言检索的常规做法。关掉可省一次 LLM 调用。
QUERY_TRANSLATION_ENABLED = True

# ============ 多模态抽取配置（文献检索助手） ============
# 传统 PyPDFLoader 只能抽纯文本：表格会变成一串错行的文字、插图直接丢失。
# 改用 PyMuPDF 后，除了正文，还能把表格转成 Markdown、把插图渲染成图片文件——
# 这样当用户问"图 3 的对比结果"时，界面上能把原图一并展示出来（证据可核验）。
ASSETS_DIR = "./assets"     # 抽出的表格/插图存放目录（加进 .gitignore）
EXTRACT_TABLES = True       # 是否抽取 PDF 表格
EXTRACT_IMAGES = True       # 是否抽取 PDF 插图
MIN_IMAGE_AREA = 12000      # 图片最小面积（pt²），用于过滤页眉 logo、分隔线等噪声
RENDER_DPI = 150            # 表格/插图渲染成预览图的分辨率
MAX_TABLE_ROWS = 40         # 表格行数上限，超过视为"误把正文判成表格"

# ============ 全局汇总问答（Global QA）配置 ============
# 【为什么需要它】标准 RAG 只能"捞 Top-K 个块"回答，天然答不了两类问题：
#   ① 全库汇总型："这些文献的共性是什么"——答案分散在全部文献里，不存在于任何单块；
#   ② 元信息型："库里都有哪些文献讲什么"——需要纵览全库，而不是最相似的 4 个块。
#   业界解法：入库时给每篇文献额外生成一份"结构化摘要"存进向量库（相当于给
#   每篇文献做一张"名片"）。遇到汇总型问题就把【全部文献的摘要】一起送进 LLM，
#   模型于是有了纵览全库的素材，这类问题就有解了。
SUMMARY_ENABLED = True            # 入库时是否为每篇文献生成摘要（关闭则跳过，省 LLM 费用）
SUMMARY_DIR = "./summaries"       # 摘要 Markdown 落盘目录（人可读，便于检查摘要质量）
SUMMARY_MAX_INPUT_CHARS = 14000   # 单次喂给 LLM 的片段字数上限（map 阶段）
SUMMARY_PARTS = 3                 # 长文献切成几段分别摘要后归并（map-reduce）
# 摘要缓存：以"文献全文的哈希"为键。文献没改过 → 直接复用上次的摘要，
# 重建时零 LLM 调用（重建从 ~100s 降到秒级的关键）；删掉 _cache.json 可强制全部重生成。
SUMMARY_CACHE_ENABLED = True
SUMMARY_WORKERS = 4               # 摘要并行线程数（LLM 调用是 IO 密集型，多线程收益显著）

# 抽取缓存：把 PDF 结构化抽取（正文/表格/插图）的结果按"文件内容哈希+抽取器版本"
# 存成 JSON。实测 4 篇文献的抽取要 ~70s（渲染插图 PNG + 全页矢量线条分析是大头），
# 文献没改过时直接读缓存，重建从 ~85s 降到 ~15s。
EXTRACT_CACHE_ENABLED = True
EXTRACT_CACHE_DIR = "./cache/extract"

GLOBAL_QA_ENABLED = True          # 是否启用"全库摘要模式"
GLOBAL_AUTO_FALLBACK = True       # 检索全部低于阈值时，自动降级为全库摘要模式
GLOBAL_MAX_DOCS = 16              # 全库摘要模式下最多带几篇文献的摘要进 Prompt
# 触发"全库汇总模式"的关键词（命中即绕过检索，直接用全部摘要作答）
GLOBAL_KEYWORDS = [
    "共性", "共同点", "共同之处", "总结", "综述", "概览", "整体上", "总体上",
    "都有什么", "都有哪些", "有哪些文献", "哪些文献", "都讲了什么", "大致讲了",
    "对比这些", "比较这些", "文献库", "知识库里", "知识库中", "研究趋势", "梳理",
]

# ============ 向量库配置 ============
VECTOR_DB_PATH = "./vector_db"   # Chroma 数据落盘目录（加进 .gitignore）
COLLECTION_NAME = "my_knowledge"  # 集合名，类似数据库里的"表名"

# ============ 路径配置 ============
DOCS_DIR = "./docs"   # 文献目录，把 PDF/TXT/MD 扔进去即可

# ============ Prompt 配置 ============
# 面向"研究生文献检索"场景：要求模型按「文献名 + 页码 + 类型」标注引用，
# 这样回答里的每句话都能回溯到原文位置（学术场景最看重可核验性）。
SYSTEM_PROMPT = """你是一位严谨的学术文献检索助手，服务对象是研究生。请遵守以下规则：

1. 只根据下面提供的【参考资料】回答，不要使用你自己的知识，也不要补充资料之外的内容。
2. 每条参考资料都标了来源（文献名 / 页码 / 类型）。引用时请写成「（文献名，第 X 页）」，
   若该条是表格则注明"表"，是插图则注明"图"。
3. 如果参考资料中没有相关内容，直接回答"根据现有文献无法回答该问题"，不要猜测。
4. 用条理清晰的中文作答；涉及数据、指标、结论时必须忠实于原文，不得编造。
5. 若检索到的资料包含表格或插图，请在回答末尾提示读者查看对应的图表（界面会同步展示）。

【参考资料】：
{context}
"""

# 全库汇总模式的专用 Prompt——此时给模型的不是"零散片段"，而是"每篇文献的名片"，
# 任务也从"阅读理解"变成了"比较归纳"，所以规则要单独写。
SYSTEM_PROMPT_GLOBAL = """你是一位严谨的学术综述助手，服务对象是研究生。
现在提供的不是零散片段，而是【文献库中每篇文献的结构化摘要】（相当于每篇的"名片"）。

请完成两件事：
1. 先逐篇用一句话概括（格式：- 《文献名》：……），让读者快速了解库里有什么；
2. 再归纳这批文献的**共性**（研究对象/方法/数据/结论上的共同点）与**明显差异**。

约束：
1. 只根据下面提供的摘要作答，不要使用你自己的知识，不要编造文献或数据。
2. 引用时写成「（文献名，摘要）」的样式，其中"文献名"要替换成上面参考资料里给出的
   真实文献名（例如：（DHyMamba_final.pdf，摘要）），不要直接写"文献名"这三个字。
   摘要里没有提到的东西，就写"摘要中未提及"，不要推测。
3. 如果某篇文献的摘要与该问题无关，可以忽略它，但要在最后说明忽略了哪些。
4. 用条理清晰的中文作答，可用小标题和列表。

【文献摘要】：
{context}
"""
